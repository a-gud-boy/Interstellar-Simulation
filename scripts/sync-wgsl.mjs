#!/usr/bin/env node
/**
 * Single-Source WGSL Wrapper Generator & Drift Guard (`scripts/sync-wgsl.mjs`).
 *
 * Reads canonical raw `.wgsl` shader files (consumed directly by Rust via `include_str!`)
 * and generates or verifies zero-fetch ES module `.wgsl.js` wrappers for WebGPU.
 *
 * Usage:
 *   node scripts/sync-wgsl.mjs --check   # Verify all .wgsl.js wrappers match canonical .wgsl (default)
 *   node scripts/sync-wgsl.mjs --write   # Regenerate all .wgsl.js wrappers from canonical .wgsl
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '..');

function normalizeWgsl(raw) {
  return `${raw.replace(/\r\n/g, '\n').replace(/\n+$/, '')}\n`;
}

function escapeTemplateLiteral(src) {
  return src.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
}

function readCanonical(relPath) {
  const full = path.join(REPO_ROOT, relPath);
  if (!fs.existsSync(full)) {
    throw new Error(`Missing canonical WGSL source: ${relPath}`);
  }
  return normalizeWgsl(fs.readFileSync(full, 'utf8'));
}

function renderSingleExport({ target, source, exportName }) {
  const src = readCanonical(source);
  return [
    `// AUTO-GENERATED by scripts/sync-wgsl.mjs from ${source}. Do not edit directly.`,
    '',
    `export const ${exportName} = /* wgsl */ \``,
    `${escapeTemplateLiteral(src)}\`;`,
    '',
  ].join('\n');
}

function renderCommonWgsl() {
  const sources = [
    ['FULLSCREEN_VERT_WGSL', 'shared/shaders/fullscreen_vert.wgsl'],
    ['MIPMAP_WGSL', 'shared/shaders/mipmap.wgsl'],
    ['NOISE_BAKE_COMPUTE_WGSL', 'shared/shaders/noise_bake.wgsl'],
  ];
  const blocks = sources.map(([name, rel]) => {
    const src = readCanonical(rel);
    return `export const ${name} = /* wgsl */ \`\n${escapeTemplateLiteral(src)}\`;`;
  });
  return [
    '// AUTO-GENERATED by scripts/sync-wgsl.mjs from shared/shaders/{fullscreen_vert,mipmap,noise_bake}.wgsl. Do not edit directly.',
    '',
    ...blocks,
    '',
  ].join('\n');
}

