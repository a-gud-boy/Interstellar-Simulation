    '    TAA_WGSL,',
    '    BLOOM_PREFILTER_WGSL,',
    '    BLOOM_DOWNSAMPLE_WGSL,',
    '    BLOOM_UPSAMPLE_WGSL,',
    '    ANAMORPHIC_WGSL,',
