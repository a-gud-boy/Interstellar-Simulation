function summarizeFirstDiff(expected, actual) {
  const expLines = expected.split('\n');
  const actLines = actual.split('\n');
  const maxLines = Math.max(expLines.length, actLines.length);
  const diffs = [];
  for (let i = 0; i < maxLines; i++) {
    if (expLines[i] !== actLines[i]) {
      diffs.push(
        `    line ${i + 1}:\n      expected: ${JSON.stringify(expLines[i] ?? '<EOF>')}\n      actual  : ${JSON.stringify(actLines[i] ?? '<EOF>')}`
      );
      if (diffs.length >= 3) break;
    }
  }
  return diffs.join('\n');
}

function parseArgs(argv) {
  let mode = 'check';
  for (const arg of argv) {
    if (arg === '-h' || arg === '--help') {
      console.log('Usage: node scripts/sync-wgsl.mjs [--check | --write]');
      process.exit(0);
    } else if (arg === '--write') {
      mode = 'write';
    } else if (arg === '--check') {
      mode = 'check';
    } else {
      console.error(`Unknown option: ${arg}`);
      process.exit(2);
    }
  }
  return mode;
}

function main() {
  const mode = parseArgs(process.argv.slice(2));
  let written = 0;
  let unchanged = 0;
  let drifted = 0;

  for (const entry of TARGETS) {
    const expected = entry.render();
    const outPath = path.join(REPO_ROOT, entry.target);
    const exists = fs.existsSync(outPath);
    const actual = exists ? fs.readFileSync(outPath, 'utf8').replace(/\r\n/g, '\n') : null;

    if (mode === 'write') {
      if (actual === expected) {
        unchanged++;
        console.log(`  [OK]   ${entry.target} (unchanged)`);
      } else {
        fs.mkdirSync(path.dirname(outPath), { recursive: true });
        fs.writeFileSync(outPath, expected, 'utf8');
        written++;
        console.log(`  [SYNC] ${entry.target}`);
      }
    } else if (!exists) {
      drifted++;
      console.error(`  [FAIL] ${entry.target} is missing.`);
    } else if (actual !== expected) {
      drifted++;
      console.error(`  [FAIL] ${entry.target} is out of sync with canonical .wgsl:`);
      console.error(summarizeFirstDiff(expected, actual));
    } else {
      unchanged++;
      console.log(`  [PASS] ${entry.target}`);
    }
  }

  if (mode === 'write') {
    console.log(`\nWGSL sync complete: ${written} updated, ${unchanged} unchanged (${TARGETS.length} total).`);
    process.exit(0);
  }

  if (drifted > 0) {
    console.error(
      `\nWGSL drift detected in ${drifted} file(s). Run: node scripts/sync-wgsl.mjs --write`
    );
    process.exit(1);
  }

  console.log(`\nWGSL check passed: ${unchanged}/${TARGETS.length} wrappers match canonical .wgsl sources.`);
}

main();
