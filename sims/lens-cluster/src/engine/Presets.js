export function getPresetById(id) {
  return PRESETS.find((p) => p.id === id) || PRESETS[2];
}

export function createInitialState(presetId = DEFAULT_STATE.presetId) {
  const preset = getPresetById(presetId);
  return {
    ...DEFAULT_STATE,
    ...preset.params,
    skyRotation: [...DEFAULT_STATE.skyRotation],
    presetId: preset.id,
  };
}
